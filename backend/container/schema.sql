SET NAMES utf8mb4;

CREATE TABLE USUARIOS (
    ID_USUARIO INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    DNI VARCHAR(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR(100) NOT NULL,
    APELLIDO VARCHAR(100) NOT NULL,
    CARGO ENUM('administrador','doctor','asistente') NOT NULL,
    CONTRASENA VARCHAR(255) NOT NULL,
    ESTADO BOOLEAN NOT NULL DEFAULT TRUE,
    FECHA_CREACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ULTIMA_SESION_TOKEN_ID CHAR(36)
);

CREATE TABLE LOG (
    ID_LOG BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    DNI_USUARIO CHAR(64) NOT NULL,
    TIPO_EVENTO VARCHAR(64) NOT NULL,
    DETALLE JSON,
    FECHA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CATALOGO_SEXOS (
    ID_SEXO VARCHAR(12) PRIMARY KEY,
    DESCRIPCION VARCHAR(100) NOT NULL
);

CREATE TABLE CATALOGO_ESTADOS_CIVIL (
    ID_ESTADO_CIVIL VARCHAR(100) PRIMARY KEY,
    DESCRIPCION VARCHAR(100) NOT NULL
);

CREATE TABLE FICHA_CLINICA (
    ID_FICHA_CLINICA INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    DNI VARCHAR(20) NOT NULL UNIQUE,
    NOMBRE_APELLIDO VARCHAR(200) NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    SEXO VARCHAR(12),
    RAZA VARCHAR(100),
    ESTADO_CIVIL VARCHAR(100),
    OCUPACION VARCHAR(150),
    NACIMIENTO VARCHAR(150),
    PROCEDENCIA VARCHAR(150),
    DOMICILIO VARCHAR(255),
    TELEFONO VARCHAR(40),
    EMAIL VARCHAR(254),
    RESPONSABLE VARCHAR(200),
    INSTITUCION VARCHAR(200),
    FECHA DATE NOT NULL
);

CREATE TABLE ANTECEDENTES (
    ID_ANTECEDENTES INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_FICHA_CLINICA INT UNSIGNED NOT NULL UNIQUE REFERENCES FICHA_CLINICA(ID_FICHA_CLINICA),
    ANTECEDENTES_FAMILIARES TEXT,
    ANTECEDENTES_PERSONALES TEXT,
    ANTECEDENTES_PERSONALES_PATOLOGICOS TEXT,
    ANTECEDENTES_PERSONALES_NO_PATOLOGICOS TEXT,
    ANTECEDENTES_ALERGICOS TEXT,
    ANTECEDENTES_QUIRURGICOS TEXT,
    ANTECEDENTES_TRANSFUSIONALES TEXT,
    ANTECEDENTES_TOXICOS TEXT,
    ANTECEDENTES_GINECO_OBSTETRICOS TEXT,
    FECHA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CITAS (
    ID_CITAS INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_FICHA_CLINICA INT UNSIGNED NOT NULL REFERENCES FICHA_CLINICA(ID_FICHA_CLINICA),
    ID_USUARIO INT UNSIGNED REFERENCES USUARIOS(ID_USUARIO),
    SERVICIO VARCHAR(150) NOT NULL,
    FECHA DATE NOT NULL,
    HORA TIME NOT NULL,
    ESTADO VARCHAR(24) NOT NULL DEFAULT 'programada',
    INDEX (FECHA, HORA)
);

CREATE TABLE CONSULTA (
    ID_CONSULTA INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_FICHA_CLINICA INT UNSIGNED NOT NULL REFERENCES FICHA_CLINICA(ID_FICHA_CLINICA),
    ID_USUARIO INT UNSIGNED NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    ES_PRIMERA_CONSULTA BOOLEAN NOT NULL DEFAULT FALSE,
    FECHA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RELATO TEXT,
    EXAMEN_FISICO_SIMPLIFICADO TEXT,
    PLAN_TRABAJO TEXT,
    ESTADO VARCHAR(24) NOT NULL DEFAULT 'pendiente',
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    ID_RECETA INT UNSIGNED,
    INDEX (ID_FICHA_CLINICA, FECHA)
);

CREATE TABLE EXAMEN_CLINICO (
    ID_EXAMEN_CLINICO INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_CONSULTA INT UNSIGNED NOT NULL UNIQUE REFERENCES CONSULTA(ID_CONSULTA),
    ID_FICHA_CLINICA INT UNSIGNED NOT NULL REFERENCES FICHA_CLINICA(ID_FICHA_CLINICA),
    PA VARCHAR(20),
    PULSO SMALLINT UNSIGNED,
    SAO2 DECIMAL(5,2),
    FR SMALLINT UNSIGNED,
    PESO DECIMAL(7,2),
    TALLA DECIMAL(6,3),
    TEMPERATURA DECIMAL(5,2),
    IMC DECIMAL(7,2),
    FECHA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CATALOGO_CIE10 (
    ID_CIE_10 INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    CODIGO VARCHAR(20) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(500) NOT NULL,
    CAPITULO VARCHAR(255),
