    ID_RECETA INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_CONSULTA INT UNSIGNED NOT NULL REFERENCES CONSULTA(ID_CONSULTA),
    ID_FICHA_CLINICA INT UNSIGNED NOT NULL REFERENCES FICHA_CLINICA(ID_FICHA_CLINICA),
    ID_USUARIO INT UNSIGNED NOT NULL REFERENCES USUARIOS(ID_USUARIO),
