);

CREATE TABLE DIAGNOSTICOS_CONSULTA (
    ID_DIAGNOSTICO INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_CONSULTA INT UNSIGNED NOT NULL REFERENCES CONSULTA(ID_CONSULTA),
    ID_CIE_10 INT UNSIGNED NOT NULL REFERENCES CATALOGO_CIE10(ID_CIE_10),
    TIPO VARCHAR(32) NOT NULL,
